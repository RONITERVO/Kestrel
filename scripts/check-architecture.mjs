import { readdirSync, readFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { checkDesktopFile, checkNativeFile } from "./architecture-rules.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const desktop = join(root, "apps/desktop/src");
const generated = join(root, "packages/generated-bindings/src");
function files(folder) {
  return readdirSync(folder, { withFileTypes: true }).flatMap((entry) => {
    const path = join(folder, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  });
}
const names = new Set(readdirSync(generated).filter((name) => name.endsWith(".ts")).map((name) => name.slice(0, -3)));
const failures = [];
for (const path of files(desktop).filter((path) => /\.[cm]?[tj]sx?$/.test(path))) {
  failures.push(...checkDesktopFile(relative(desktop, path), readFileSync(path, "utf8"), names));
}
for (const folder of ["src-tauri/src", "src-tauri/build", "crates/app-core/src"]) {
  for (const path of files(join(root, folder)).filter((path) => path.endsWith(".rs"))) {
    failures.push(...checkNativeFile(relative(root, path).replaceAll("\\", "/"), readFileSync(path, "utf8")));
  }
}
failures.push(...checkNativeFile("src-tauri/build.rs", readFileSync(join(root, "src-tauri/build.rs"), "utf8")));
for (const path of files(generated).filter((path) => path.endsWith(".ts"))) {
  if (!readFileSync(path, "utf8").startsWith("// This file was generated by") && !path.endsWith("index.ts")) failures.push(`${path}: Unrecognized generated binding.`);
}
if (failures.length) throw new Error(`Architecture checks failed:\n${failures.map((message) => `  - ${message}`).join("\n")}`);
console.log("Architecture boundaries pass: no handwritten contract quarantine; native transport, storage and import layers checked.");
