import { createHash } from "node:crypto";
import { readdirSync, readFileSync } from "node:fs";
import { join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const repositoryRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const desktopSource = join(repositoryRoot, "apps", "desktop", "src");
const contractsPath = join(desktopSource, "contracts", "index.ts");
const generatedRoot = join(repositoryRoot, "packages", "generated-bindings", "src");
const legacyContractNamesHash = "a0aa4974c3b8d798edac4cbc7b1549bc1ee30ae49cf8d0f70d83d5799656b2ab";

function files(root, cursor = root) {
  return readdirSync(cursor, { withFileTypes: true }).flatMap((entry) => {
    const path = join(cursor, entry.name);
    return entry.isDirectory() ? files(root, path) : [path];
  });
}

const failures = [];
const contractSource = readFileSync(contractsPath, "utf8");
const contractTree = ts.createSourceFile(contractsPath, contractSource, ts.ScriptTarget.Latest, true);
const legacyNames = contractTree.statements
  .filter((statement) => ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement))
  .map((statement) => statement.name.text)
  .sort();

if (new Set(legacyNames).size !== legacyNames.length) {
  failures.push("The quarantined TypeScript contract file contains duplicate declarations.");
}
const actualLegacyHash = createHash("sha256").update(legacyNames.join("\n")).digest("hex");
if (actualLegacyHash !== legacyContractNamesHash) {
  failures.push("The quarantined TypeScript contract set changed. New application contracts must be defined in Rust and generated; when removing migrated declarations, update the recorded hash deliberately.");
}

for (const path of files(desktopSource).filter((path) => /\.(?:ts|tsx)$/.test(path) && path !== contractsPath)) {
  if (readFileSync(path, "utf8").includes("@kestrel/generated-bindings")) {
    failures.push(`${relative(repositoryRoot, path)} bypasses the desktop contract facade.`);
  }
}

for (const path of files(generatedRoot).filter((path) => path.endsWith(".ts") && !path.endsWith("index.ts"))) {
  if (!readFileSync(path, "utf8").startsWith("// This file was generated by")) {
    failures.push(`${relative(repositoryRoot, path)} is not a recognized Rust-generated binding.`);
  }
}

if (failures.length) {
  throw new Error(`Architecture checks failed:\n${failures.map((failure) => `  - ${failure}`).join("\n")}`);
}

console.log(`Architecture boundary is intact (${legacyNames.length} quarantined TypeScript contracts remain to migrate).`);
