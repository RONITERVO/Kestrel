import { execFileSync } from "node:child_process";
import { cpSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { basename, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const committedRoot = join(repositoryRoot, "packages", "generated-bindings", "src");
const check = process.argv.includes("--check");
const outputRoot = mkdtempSync(join(tmpdir(), "kestrel-bindings-"));

function listFiles(root, cursor = root) {
  return readdirSync(cursor, { withFileTypes: true })
    .flatMap((entry) => {
      const path = join(cursor, entry.name);
      return entry.isDirectory() ? listFiles(root, path) : [relative(root, path).replaceAll("\\", "/")];
    })
    .sort();
}

function writeIndex(root) {
  const exports = readdirSync(root, { withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".ts") && !["index.ts", "defaults.ts"].includes(entry.name))
    .map((entry) => basename(entry.name, ".ts"))
    .sort()
    .map((name) => `export type { ${name} } from "./${name}.js";`);
  writeFileSync(
    join(root, "index.ts"),
    `// Generated from Rust by scripts/generate-bindings.mjs. Do not edit.\nexport { speechPreferencesDefaults, movieProducerDefaults, runtimePolicyCatalog, externalCollaborationFormat } from "./defaults.js";\n${exports.join("\n")}\n`,
  );
}

function normalizeGenerated(root) {
  for (const path of listFiles(root).filter((name) => name.endsWith(".ts"))) {
    const absolute = join(root, path);
    const normalized = readFileSync(absolute, "utf8")
      .replaceAll("\r\n", "\n")
      .replace(/[ \t]+$/gm, "")
      .replace(/\s+$/, "\n");
    writeFileSync(absolute, normalized);
  }
}

function writeIpcMaps(root, metadata) {
  writeFileSync(join(root, "defaults.ts"), `// This file was generated by the Rust IPC boundary. Do not edit.\nimport type { SpeechPreferences } from "./SpeechPreferences.js";\nimport type { MovieProducerProjectSettings } from "./MovieProducerProjectSettings.js";\nimport type { RuntimePolicyCatalog } from "./RuntimePolicyCatalog.js";\nimport type { ExternalCollaborationFormat } from "./ExternalCollaborationFormat.js";\nexport const movieProducerDefaults: MovieProducerProjectSettings = ${JSON.stringify(metadata.movieProducerDefaults, null, 2)};\nexport const speechPreferencesDefaults: SpeechPreferences = ${JSON.stringify(metadata.speechPreferencesDefaults, null, 2)};\nexport const runtimePolicyCatalog: RuntimePolicyCatalog = ${JSON.stringify(metadata.runtimePolicyCatalog, null, 2)};\nexport const externalCollaborationFormat: ExternalCollaborationFormat = ${JSON.stringify(metadata.externalCollaborationFormat, null, 2)};\n`);
  const importsFor = (body) => readdirSync(root)
    .filter((file) => file.endsWith(".ts") && !["index.ts", "defaults.ts"].includes(file))
    .map((file) => basename(file, ".ts"))
    .filter((name) => new RegExp(`\\b${name}\\b`).test(body))
    .sort()
    .map((name) => `import type { ${name} } from "./${name}.js";`)
    .join("\n");
  const commands = metadata.commands.sort((a, b) => a.name.localeCompare(b.name)).map((command) => {
    const args = command.args.length
      ? `{ ${command.args.map((arg) => `${arg.name}${arg.optional ? "?" : ""}: ${arg.type}`).join("; ")} }`
      : "Record<string, never>";
    return `  ${command.name}: { args: ${args}; result: ${command.result} };`;
  });
  const events = metadata.events.sort((a, b) => a.name.localeCompare(b.name))
    .map((event) => `  "${event.name}": ${event.type};`);
  for (const [name, lines] of [["DesktopCommands", commands], ["DesktopEvents", events]]) {
    const body = `export type ${name} = {\n${lines.join("\n")}\n};\n`;
    writeFileSync(join(root, `${name}.ts`), `// This file was generated by the Rust IPC boundary. Do not edit.\n${importsFor(body)}\n\n${body}`);
  }
}

try {
  execFileSync("cargo", ["test", "-p", "kestrel-app-core"], {
    cwd: repositoryRoot,
    env: {
      ...process.env,
      TS_RS_EXPORT_DIR: outputRoot,
      TS_RS_IMPORT_EXTENSION: "js",
      TS_RS_LARGE_INT: "number",
    },
    stdio: "inherit",
  });
  const metadataPath = join(outputRoot, "ipc-metadata.json");
  execFileSync("cargo", ["test", "--lib", "--manifest-path", "src-tauri/Cargo.toml", "export_command_bindings", "--", "--exact"], {
    cwd: repositoryRoot,
    env: { ...process.env, KESTREL_IPC_EXPORT_PATH: metadataPath, TS_RS_LARGE_INT: "number" },
    stdio: "inherit",
  });
  writeIpcMaps(outputRoot, JSON.parse(readFileSync(metadataPath, "utf8")));
  rmSync(metadataPath);
  normalizeGenerated(outputRoot);
  writeIndex(outputRoot);

  if (check) {
    const expected = listFiles(outputRoot);
    const actual = listFiles(committedRoot);
    const names = [...new Set([...expected, ...actual])].sort();
    const changed = names.filter((name) => {
      if (!expected.includes(name) || !actual.includes(name)) return true;
      return readFileSync(join(outputRoot, name), "utf8") !== readFileSync(join(committedRoot, name), "utf8").replaceAll("\r\n", "\n");
    });
    if (changed.length) {
      throw new Error(`Rust/TypeScript bindings are stale:\n${changed.map((name) => `  ${name}`).join("\n")}\nRun npm run bindings:generate.`);
    }
  } else {
    rmSync(committedRoot, { recursive: true, force: true });
    mkdirSync(committedRoot, { recursive: true });
    cpSync(outputRoot, committedRoot, { recursive: true });
  }
} finally {
  rmSync(outputRoot, { recursive: true, force: true });
}
